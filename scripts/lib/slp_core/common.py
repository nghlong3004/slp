"""Configuration and filesystem primitives; no provider-specific behavior."""

from dataclasses import dataclass
from datetime import date, datetime, time
import json
import os
from pathlib import Path
import shutil
import tempfile
import tomllib


class SlpError(Exception):
    pass


def atomic_write(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def toml_value(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{toml_value(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    raise SlpError(f"Unsupported TOML value: {type(value).__name__}")


def dump_toml(config):
    # Fully quoted keys preserve project paths, dotted names, and nested tables.
    text = "# Generated by SLP; edit the source configuration.\n" + "".join(
        f"{toml_value(key)} = {toml_value(value)}\n" for key, value in config.items()
    )
    tomllib.loads(text)
    return text


def read_toml(path):
    with Path(path).open("rb") as stream:
        return tomllib.load(stream)


def xdg_home(variable, fallback):
    value = os.environ.get(variable, "")
    # XDG ignores empty or relative values; defaults remain user-specific.
    return Path(value) if value and Path(value).is_absolute() else Path(fallback)


def state_home():
    return xdg_home("XDG_STATE_HOME", Path.home() / ".local/state") / "slp"


def check_link(path, target):
    if not target.exists():
        raise SlpError(f"Shared target does not exist: {target}")
    if path.exists() and not path.is_symlink():
        raise SlpError(f"Refusing to replace private non-symlink path: {path}")


def shared_link(path, target):
    check_link(path, target)
    if path.is_symlink():
        if path.resolve() == target.resolve():
            return
        path.unlink()
    path.symlink_to(target)


@dataclass
class Installation:
    root: Path
    config: Path
    runtime: Path
    settings: dict

    @classmethod
    def load(cls):
        root = Path(os.environ.get("SLP_ROOT", Path(__file__).resolve().parents[3])).expanduser().resolve()
        config = Path(os.environ.get("SLP_CONFIG_HOME", root / "config")).expanduser().resolve()
        runtime = Path(os.environ.get("SLP_RUNTIME_ROOT") or state_home() / "runtime").expanduser().resolve()
        legacy = root / ".runtime"
        if not os.environ.get("SLP_RUNTIME_ROOT") and legacy.exists() and legacy.resolve() != runtime:
            raise SlpError("Legacy runtime needs migration; run scripts/install before launching or syncing")
        settings = read_toml(config / "slp.toml")
        if settings.get("version") != 2 or not settings.get("roles"):
            raise SlpError("Expected SLP version=2 and at least one configured role")
        return cls(root, config, runtime, settings)

    def provider(self, name=None, allow_disabled=False):
        name = name or self.settings["default_provider"]
        if not name or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in name):
            raise SlpError(f"Invalid provider name: {name}")
        path = self.config / "providers" / f"{name}.toml"
        if not path.is_file():
            raise SlpError(f"Provider is not configured: {name}")
        provider = read_toml(path)
        if provider.get("id") != name:
            raise SlpError(f"Provider id does not match its filename: {path}")
        if not allow_disabled and not provider.get("enabled", False):
            raise SlpError(f"Provider is disabled: {name}")
        return provider

    def providers(self):
        return [self.provider(path.stem) for path in sorted((self.config / "providers").glob("*.toml"))
                if read_toml(path).get("enabled", False)]

    def role(self, name):
        if name not in self.settings["roles"]:
            raise SlpError(f"Unknown role: {name}")
        return self.settings["roles"][name]

    def role_prompt(self, role):
        self.role(role)
        text = (self.config / "shared.md").read_text() + "\n\n" + (self.config / "roles" / f"{role}.md").read_text()
        return text.replace("{{config_home}}", str(self.config)).rstrip() + "\n"

    def role_runtime(self, provider, role):
        self.role(role)
        path = self.runtime / provider["id"] / role
        if (self.runtime / provider["id"]).is_symlink() or path.is_symlink():
            raise SlpError(f"Runtime directory must not be a symlink: {path}")
        return path

    def binary(self, provider):
        command = list(provider["command"])
        override = os.environ.get(provider.get("binary_env", ""))
        command[0] = os.path.expanduser(override or command[0])
        binary = shutil.which(command[0])
        if not binary:
            raise SlpError(f"Provider binary not found: {command[0]}")
        command[0] = str(Path(binary).absolute())
        return command

    def defaults(self, provider, role, models):
        config = self.role(role)
        if config.get("provider") == provider["id"]:
            model_id, effort = config.get("model"), config.get("effort")
        else:
            model_id, effort = provider.get("default_model"), provider.get("default_effort")
        if not model_id:
            if not models:
                raise SlpError(f"No model catalog configured for {provider['id']}")
            model_id = models[0]["id"]
        model = next((m for m in models if m["id"] == model_id), None)
        if model is None:
            raise SlpError(f"Configured default model is absent from {provider['id']} catalog: {model_id}")
        effort = effort or model.get("default_effort")
        if effort and effort not in [e["id"] for e in model.get("efforts", [])]:
            raise SlpError(f"Unsupported effort {effort} for {model_id}")
        return model_id, effort

    def launcher(self, provider):
        return self.runtime / provider["id"] / "launch"

    def write_launcher(self, provider):
        # Paseo sometimes probes only argv[0] with --version. A per-provider
        # executable keeps those probes routed to the correct CLI as well.
        env = {"SLP_ROOT": str(self.root), "SLP_CONFIG_HOME": str(self.config),
               "SLP_RUNTIME_ROOT": str(self.runtime)}
        if provider.get("binary_env"):
            env[provider["binary_env"]] = self.binary(provider)[0]
        script = str(self.root / "scripts/slp")
        text = ("#!/usr/bin/env python3\nimport os, sys\n"
                f"os.environ.update({env!r})\n"
                f"os.execv({script!r}, [{script!r}, '--provider', {provider['id']!r}, *sys.argv[1:]])\n")
        path = self.launcher(provider)
        if path.parent.is_symlink():
            raise SlpError(f"Provider runtime must not be a symlink: {path.parent}")
        atomic_write(path, text)
        path.chmod(0o755)
        return path


def provider_id(provider, role):
    return provider.get("provider_ids", {}).get(role, f"slp-{provider['id']}-{role}")
